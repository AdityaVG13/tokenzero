#!/usr/bin/env bash
# Code-execution vs MCP-schema token bake-off (bead tokenzero-da8.1)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
H=(python3 -m benchmarks.harness)
BIN="$("${H[@]}" resolve_bin)" || { echo "ERROR: tokenzero binary not found. Set TOKENZERO_BIN=/path/to/tokenzero" >&2; exit 1; }
CORPUS_FILE="${ROOT}/README.md"; CARGO_FILE="${ROOT}/Cargo.toml"
EDIT_TMP="$(mktemp /tmp/tz-bakeoff-edit.XXXXXX)"; CAP_FILE="$(mktemp /tmp/tz-bakeoff-cap.XXXXXX)"
trap 'rm -f "$EDIT_TMP" "$CAP_FILE"' EXIT
log() { printf '[bakeoff] %s\n' "$*" >&2; }
tok() { printf '%s' "$1" | "${H[@]}" tok; }
now_ms() { "${H[@]}" now_ms; }
emit_row() { printf '| `%s` | `%s` | %s | %s | %s | %s | %s |\n' "$1" "$2" "$3" "$4" "$5" "$6" "$7"; }
cap_start=$(now_ms); "$BIN" capabilities --json > "$CAP_FILE" || { echo "ERROR: capabilities --json failed" >&2; exit 1; }
MCP_WALL=$(( $(now_ms) - cap_start ))
mcp_tok() { "${H[@]}" mcp_schema_tokens "$CAP_FILE" "$1"; }
quality_check() { printf '%s' "$2" | "${H[@]}" quality "$1"; }

cli_one() {
  local task="$1" cmd_str="$2"; shift 2
  local start end out status=0
  start=$(now_ms); out=$("$@") || status=$?; end=$(now_ms)
  local out_tok; out_tok=$(printf '%s' "$out" | "${H[@]}" accounting 2>/dev/null || echo 0)
  local q; if [[ $status -ne 0 ]]; then q=FAIL; else q=$(quality_check "$task" "$out"); fi
  printf '%s\t%s\t%s\t%s\t%s\n' "$(tok "$cmd_str")" "$out_tok" 1 "$((end-start))" "$q"
}
sum_rows() {
  local in_t=0 out_t=0 turns=0 wall=0 q=PASS i o t w qu
  while IFS=$'\t' read -r i o t w qu; do
    in_t=$((in_t+i)); out_t=$((out_t+o)); turns=$((turns+t)); wall=$((wall+w)); [[ "$qu" == PASS ]] || q=FAIL
  done
  printf '%s\t%s\t%s\t%s\t%s\n' "$in_t" "$out_t" "$turns" "$wall" "$q"
}
run_codemode() {
  local task="$1" plan="$2" start end out status=0
  start=$(now_ms); out=$("$BIN" codemode --json "$plan") || status=$?; end=$(now_ms)
  local out_tok turns q
  out_tok=$(printf '%s' "$out" | python3 -c 'import sys,json; d=json.load(sys.stdin); print(d.get("value",{}).get("raw_tokens", d.get("telemetry",{}).get("raw_tokens",0)))' 2>/dev/null || echo 0)
  turns=$(printf '%s' "$out" | python3 -c 'import sys,json; d=json.load(sys.stdin); print(d.get("telemetry",{}).get("logical_ops",1))' 2>/dev/null || echo 1)
  if [[ $status -ne 0 ]]; then q=FAIL; else q=$(quality_check "$task" "$out"); fi
  emit_row "$task" CodeMode "$(tok "$plan")" "$out_tok" "$turns" "$((end-start))" "$q"
}
emit_cli() { local task="$1"; shift; local r i o t w q; r=$("$@"); IFS=$'\t' read -r i o t w q <<<"$r"; emit_row "$task" CLI "$i" "$o" "$t" "$w" "$q"; }
setup_edit() { printf 'alpha\nbeta\ngamma\n' > "$EDIT_TMP"; }

log "binary: $BIN"; log "corpus: $CORPUS_FILE , $CARGO_FILE"
printf '# Code-Exec vs MCP-Schema Bake-off Results\n\n'
printf '> Bead: tokenzero-da8.1 — generated by `benchmarks/code-exec-vs-mcp-bakeoff.sh`\n'
printf '> Baseline commit: %s\n\n' "$("${H[@]}" git_commit --short)"
printf '| Task | Approach | input_tokens | output_tokens | turns | wall_ms | quality |\n'
printf '|---|---|---:|---:|---:|---:|---|\n'

# --- tasks (same commands/quality contracts as original) ---
task=read_file
emit_row "$task" MCP-schema "$(mcp_tok read)" 0 1 "$MCP_WALL" simulated
emit_cli "$task" cli_one "$task" "$BIN read $CARGO_FILE --end-line 20 --json" "$BIN" read "$CARGO_FILE" --end-line 20 --json
run_codemode "$task" 'const f = await zero.read("'"$CARGO_FILE"'", { end_line: 20 }); return f;'

task=search_filter
emit_row "$task" MCP-schema "$(mcp_tok find,grep)" 0 1 "$MCP_WALL" simulated
emit_cli "$task" cli_one "$task" "$BIN find TokenZero $CORPUS_FILE --json" "$BIN" find TokenZero "$CORPUS_FILE" --json
run_codemode "$task" 'const h = await zero.find("TokenZero", "'"$CORPUS_FILE"'"); return h;'

task=edit_verify
emit_row "$task" MCP-schema "$(mcp_tok edit,read)" 0 1 "$MCP_WALL" simulated
setup_edit
row=$(
  cli_one "$task" "$BIN edit --edits-json [{find:beta,replace:BETA}] --json $EDIT_TMP" \
    "$BIN" edit --edits-json '[{"find":"beta","replace":"BETA"}]' --json "$EDIT_TMP"
  cli_one "$task" "$BIN read $EDIT_TMP --json" "$BIN" read "$EDIT_TMP" --json
)
IFS=$'\t' read -r i o t w q <<<"$(printf '%s' "$row" | sum_rows)"; emit_row "$task" CLI "$i" "$o" "$t" "$w" "$q"
setup_edit
run_codemode "$task" 'const e = await zero.edit("'"$EDIT_TMP"'", [{ find: "beta", replace: "BETA" }]); const f = await zero.read("'"$EDIT_TMP"'"); return f;'

task=multi_step_nav
emit_row "$task" MCP-schema "$(mcp_tok tree,read,find)" 0 1 "$MCP_WALL" simulated
row=$(
  cli_one "$task" "$BIN tree $ROOT --depth 2 --json" "$BIN" tree "$ROOT" --depth 2 --json
  cli_one "$task" "$BIN read $CARGO_FILE --json" "$BIN" read "$CARGO_FILE" --json
  cli_one "$task" "$BIN find workspace $CARGO_FILE --json" "$BIN" find workspace "$CARGO_FILE" --json
)
IFS=$'\t' read -r i o t w q <<<"$(printf '%s' "$row" | sum_rows)"; emit_row "$task" CLI "$i" "$o" "$t" "$w" "$q"
run_codemode "$task" 'const t = await zero.tree("'"$ROOT"'", { depth: 2 }); const f = await zero.read("'"$CARGO_FILE"'"); const hits = await zero.find("workspace", "'"$CARGO_FILE"'"); return hits;'

task=shell_expand
emit_row "$task" MCP-schema "$(mcp_tok run,expand,read)" 0 1 "$MCP_WALL" simulated
row=$(
  cli_one "$task" "$BIN run --json -- find . -maxdepth 1 -name Cargo.toml" \
    "$BIN" run --json -- find . -maxdepth 1 -name Cargo.toml
  cli_one "$task" "$BIN read $CARGO_FILE --end-line 1 --json" "$BIN" read "$CARGO_FILE" --end-line 1 --json
)
IFS=$'\t' read -r i o t w q <<<"$(printf '%s' "$row" | sum_rows)"; emit_row "$task" CLI "$i" "$o" "$t" "$w" "$q"
run_codemode "$task" 'const out = await zero.shell("find . -maxdepth 1 -name Cargo.toml"); const f = await zero.expand(out.ref); return f;'

printf '\n_Legend: quality = PASS/FAIL for executed approaches; `simulated` = MCP schema load only (no task execution)._\n'
log done.
